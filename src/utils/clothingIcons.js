// Иконка-эмодзи для вещи из советов по одежде. Порядок правил важен:
// срабатывает первое подходящее.
const RULES = [
  [/зонт/i, '☂️'],
  [/очки/i, '🕶️'],
  [/крем|spf/i, '🧴'],
  [/вод[ыа]/i, '💧'],
  [/варежк|перчатк/i, '🧤'],
  [/шарф|снуд/i, '🧣'],
  [/кепк|панам|головной убор/i, '🧢'],
  [/шапк/i, '🧶'],
  [/носк/i, '🧦'],
  [/сандал|открытая обувь/i, '🩴'],
  [/кроссовк|кед/i, '👟'],
  [/ботинк|обувь/i, '🥾'],
  [/шорт/i, '🩳'],
  [/брюк|джинс|юбк/i, '👖'],
  [/куртк|пуховик|пальто|дождевик|ветровк/i, '🧥'],
  [/свитер|толстовк|худи|кардиган|флис/i, '🧶'],
  [/рубашк/i, '👔'],
  [/футболк|лонгслив|термобель|одежда/i, '👕'],
];

export function iconFor(text) {
  const rule = RULES.find(([re]) => re.test(text));
  return rule ? rule[1] : '✨';
}
