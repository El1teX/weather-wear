// Короткая погодная приписка к вечерним и ночным пожеланиям
const LATE_WEATHER = {
  rain: 'Под шум дождя отдыхается особенно хорошо.',
  snow: 'Утром тротуары могут быть скользкими — выходите чуть раньше.',
  storm: 'Закройте окна: за окном гроза.',
  fog: 'Если собираетесь в дорогу, помните о тумане.',
};

function greetingFor(hour) {
  if (hour >= 5 && hour < 12) return 'Доброе утро';
  if (hour >= 12 && hour < 18) return 'Добрый день';
  if (hour >= 18 && hour < 23) return 'Добрый вечер';
  return 'Доброй ночи';
}

// Простой хэш строки, чтобы выбор пожелания не менялся
// при каждом обновлении погоды в течение дня.
function hash(str) {
  let h = 0;
  for (let i = 0; i < str.length; i += 1) h = (h * 31 + str.charCodeAt(i)) >>> 0;
  return h;
}

const pick = (list, seed) => list[seed % list.length];

/**
 * Пожелание на день с учётом погоды и местного времени в городе.
 * @returns {{ greeting: string, text: string }}
 */
export function getDayWish(weather, cityName = '') {
  // weather.time — местное время города в формате 2026-09-30T14:15
  const hour = Number(weather.time.slice(11, 13));
  const date = weather.time.slice(0, 10);
  const { sky } = describeWeather(weather.code);
  const greeting = greetingFor(hour);
  const seed = hash(`${date}|${cityName}|${sky}`);
  const isNight = hour >= 23 || hour < 5;
  const isEvening = hour >= 18 && !isNight;

  if (isNight || isEvening) {
    const parts = [pick(isNight ? NIGHT_LINES : EVENING_LINES, seed)];
    if (LATE_WEATHER[sky]) parts.push(LATE_WEATHER[sky]);
    return { greeting, text: parts.join(' ') };
  }

  const feels = Math.round(weather.feelsLike);
  let text;
  if (feels >= 28 && (sky === 'clear' || sky === 'clouds')) text = pick(HOT_LINES, seed);
  else if (feels <= -15 && sky !== 'storm') text = pick(FROST_LINES, seed);
  else text = pick(DAY_LINES[sky] ?? DAY_LINES.clouds, seed);

  return { greeting, text };
}
